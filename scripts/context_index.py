#!/usr/bin/env python3
"""Generate context/INDEX.md from the records in context/.

One line per decision and per question, so CLAUDE.md can import the index
instead of every record; Claude opens a record when a task needs it.
INDEX.md is output, never edited by hand: rerun this script after adding or
changing a record.

Usage (from anywhere in the repo):
  scripts/context_index.py           write context/INDEX.md
  scripts/context_index.py --check   exit 1 if INDEX.md is out of date

Standard library only. Frontmatter is the restricted form the records use:
'key: value' lines, values as null, a bare word, a "JSON string" or [a, b].
"""

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

DREF = re.compile(r"\bD\d+\b")


def fail(msg):
    print(f"context_index: {msg}", file=sys.stderr)
    sys.exit(2)


def parse_value(v):
    v = v.strip()
    if v == "null":
        return None
    if v.startswith('"'):
        return json.loads(v)
    if v.startswith("["):
        inner = v[1:-1].strip()
        return [x.strip() for x in inner.split(",")] if inner else []
    return v


def read_record(path):
    text = path.read_text(encoding="utf-8")
    m = re.match(r"\A---\n(.*?)\n---\n(.*)\Z", text, re.S)
    if not m:
        fail(f"{path}: no frontmatter")
    fm = {}
    for line in m.group(1).split("\n"):
        key, sep, val = line.partition(":")
        if not sep:
            fail(f"{path}: bad frontmatter line {line!r}")
        fm[key.strip()] = parse_value(val)
    return fm, m.group(2)


def records(folder):
    # TEMPLATE.md and anything starting with '_' are not records.
    for p in sorted(folder.glob("*.md")):
        if p.name == "TEMPLATE.md" or p.name.startswith("_"):
            continue
        yield p, *read_record(p)


def cell(s):
    return s.replace("|", "\\|")


def build(ctx):
    lines = ["# Context index", "",
             "Generated by `scripts/context_index.py`. Don't edit by hand; "
             "rerun the script after changing anything in `context/`.", ""]

    decs = []
    for p, fm, body in records(ctx / "decisions"):
        decs.append((int(fm["id"][1:]), p, fm))
    decs.sort()
    lines += ["## Decisions", "",
              "| ID | Title | Status | Date |",
              "| --- | --- | --- | --- |"]
    for _, p, fm in decs:
        status = fm["status"]
        if fm.get("superseded_by"):
            status += f" by {fm['superseded_by']}"
        link = f"[{fm['id']}](decisions/{p.name})"
        lines.append(f"| {link} | {cell(fm['title'])} | {status} | "
                     f"{fm.get('date') or ''} |")

    qs = list(records(ctx / "questions"))
    sections = [("Open questions", "open"), ("Deferred", "deferred"),
                ("Resolved", "resolved")]
    for heading, status in sections:
        rows = [(p, fm, body) for p, fm, body in qs if fm["status"] == status]
        lines += ["", f"## {heading}", ""]
        if not rows:
            lines.append("None.")
            continue
        lines += ["| Question | Group | Mentions |", "| --- | --- | --- |"]
        for p, fm, body in rows:
            refs = fm.get("resolved_by") or []
            for r in DREF.findall(body):
                if r not in refs:
                    refs.append(r)
            refs.sort(key=lambda r: int(r[1:]))
            lines.append(f"| [{cell(fm['title'])}](questions/{p.name}) | "
                         f"{fm.get('group', '')} | {', '.join(refs)} |")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if INDEX.md is out of date")
    args = ap.parse_args()
    try:
        root = subprocess.run(["git", "rev-parse", "--show-toplevel"],
                              capture_output=True, text=True,
                              check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        fail("run this from inside the wipeOS git repo")
    ctx = Path(root) / "context"
    if not (ctx / "decisions").is_dir():
        fail("context/decisions not found")

    new = build(ctx)
    index = ctx / "INDEX.md"
    if args.check:
        if not index.exists() or index.read_text(encoding="utf-8") != new:
            print("context/INDEX.md is out of date; "
                  "run scripts/context_index.py", file=sys.stderr)
            sys.exit(1)
        return
    index.write_text(new, encoding="utf-8")
    print(f"Wrote {index.relative_to(root)}.")


if __name__ == "__main__":
    main()
